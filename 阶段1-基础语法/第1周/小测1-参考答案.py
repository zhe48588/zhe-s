# ---------- 第5题:分支结构 ----------
# 你的错误:①没把输入转成数字 ②边界(90/75/60 本身)判错
g = float(input("输入成绩:"))     # ① 转成数字!
if g >= 90:                      # ② 用 >= ,让 90 分属于"优秀"
    print("优秀")
elif g >= 75:                    # 上一分支不成立说明 g<90,所以这里只需 g>=75
    print("良好")
elif g >= 60:
    print("及格")
else:
    print("不及格")
# 技巧:if-elif 从高到低排列时,后面的条件会自动"继承"前面的否定,不用写区间

