#认识数据类型
#由函数type检验数据类型
#int --整型
num1=1
print(type(num1))
#float --浮点型
num2=1.1
print(type(num2))
#str --字符串
a="zhe"  #数据要带引号
print(type(a))
#bool --布尔型，两个，Ture False判断时使用
b=True
print(type(b))
c=False
print(type(c))
#list --列表
d=[1,2,3]
print(type(d))
#tuple --元组
e=(4,5,6)
print(type(e))
#set -- 集合
f={7,8,9}
print(type(f))
#####中括号[]为列表，小括号()为元组,{}为集合
g={'name':'zhe','age':19}
print(type(g))

