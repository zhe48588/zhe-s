#语法：序列[开始位置下标:结束位置下标:步长]
#不包含结束位置下标
#步长是选取间隔，正负数都可以，默认为1，可以不写
str1='012345678'
print(str1[2:5:1])#234
print(str1[2:5:2])#24
print(str1[:5])#01234--不写开始默认从0开始取
print(str1[2:])#2345678--不写结束表示选取到最后
print(str1[:])#012345678--选取全部
#负数
print(str1[::-1])#步长为负数则为倒序
print(str1[-4:-1])#567--负1表示最后一个数据。依次向前
print(str1[-4:-1:-1])#步长为负数，选取方向与步长方向相反，无法获得数据
print(str1[-1:-4:-1])
