i=1
while i<=9:
    j=1
    while j<=i:
        print(f'{i}*{j}=={i*j}',end='\t')#\t保证输出内容对齐
        j+=1
    print()#空print起换行作用
    i+=1
"""
先判断i是否小于9 进入外层循环，再判断j<=i进入内层循环
一开始i<9进入外层循环 j=1 判断j<=i也就是1<=1，进入内层循环
打印1*1=1，j变成2，2<=1不成立，退出内层循环，执行i+=1，i变为2
2<=9 进入外层循环，判断j<=i
j=1 1<=2 打印2*1=2  j变为2
判断2<=2 打印2*2=4   j变为3，3<=2不成立，退出内层循环，执行i+=1，i变为3
以此类推
"""

