# ---------- 第5题:if-elif-else 判断年龄(20分)----------
# 题目:输入年龄,按规则输出:
# 0-6 岁 → 儿童
# 7-17 岁 → 少年
# 18-59 岁 → 青年
# 60 岁及以上 → 老年
# 提示:① 记得把输入转成数字!② 注意边界 ③ else 后面不写条件
# 示例:输入 18 → 输出 青年

# 你的答案:
age = int(input('输入年龄：'))
if 0<= age <=6 :
    print('儿童')
elif 7<= age <=17 :
    print('少年')
elif 18<= age <=59 :
    print('青年') 
else :
    print('老年')



